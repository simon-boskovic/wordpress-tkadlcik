/**
 * Site paths in the generated graph ("/akce/#webpage") become absolute URLs on the current host
 * (protocol-relative "//…" and absolute URLs stay as they are).
 *
 * @param mixed $node Graph node or value.
 * @return mixed
 */
function tk_schema_absolutize( $node ) {
	if ( is_array( $node ) ) {
		foreach ( $node as $key => $value ) {
			$node[ $key ] = tk_schema_absolutize( $value );
		}
		return $node;
	}

	if ( is_string( $node ) && isset( $node[0] ) && '/' === $node[0] && ( ! isset( $node[1] ) || '/' !== $node[1] ) ) {
		return home_url( $node );
	}

	return $node;
}

/**
 * The page's JSON-LD @graph (data/schema.json, generated by build/seo.mjs buildSchema) with what only WordPress
 * knows added: the page node's dateModified (= post_modified, the sitemap's <lastmod>; page-upsert writes a page
 * only when it really changed) and the organisation's logo (the site icon, `wp tk site-icon`). Paths are
 * absolutized. Empty array when there is no graph for this request.
 *
 * @return array
 */
function tk_schema_graph() {
	if ( ! is_singular( 'page' ) ) {
		return array();
	}

	$all  = tk_theme_json( 'schema.json' );
	$slug = (string) get_post_field( 'post_name', get_queried_object_id() );

	if ( empty( $all[ $slug ] ) || ! is_array( $all[ $slug ] ) ) {
		return array();
	}

	$graph    = $all[ $slug ];
	$modified = get_post_datetime( get_queried_object_id(), 'modified' );
	$icon     = get_site_icon_url( 512 );

	foreach ( $graph as $i => $node ) {
		$id = isset( $node['@id'] ) && is_string( $node['@id'] ) ? $node['@id'] : '';
		if ( $modified && '#webpage' === substr( $id, -8 ) ) {
			$graph[ $i ]['dateModified'] = $modified->format( DATE_ATOM );
		}
		if ( $icon && '/#organization' === $id && empty( $node['logo'] ) ) {
			$graph[ $i ]['logo'] = array(
				'@type'      => 'ImageObject',
				'url'        => $icon,
				'contentUrl' => $icon,
				'width'      => 512,
				'height'     => 512,
			);
		}
	}

	return tk_schema_absolutize( $graph );
}

/**
 * One JSON-LD @graph per page (TSF's own JSON-LD is switched off by wp tk seo-setup).
 */
function tk_print_schema() {
	$graph = tk_schema_graph();
	if ( ! $graph ) {
		return;
	}

	$data = array(
		'@context' => 'https://schema.org',
		'@graph'   => $graph,
	);

	echo '<script type="application/ld+json">' . wp_json_encode( $data, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_HEX_TAG ) . "</script>\n"; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- JSON, tags hex-escaped.
}
add_action( 'wp_head', 'tk_print_schema', 20 );

/**
 * /llms.txt — plain-text site summary for AI assistants, generated into data/llms.txt ({{home}} = home_url()).
 * WordPress sees the request because .htaccess routes non-existent files to index.php. Cache-Control
 * (public, max-age=3600) is set earlier on init by the page cache plugin for this path, like robots.txt.
 */
function tk_serve_llms_txt() {
	$uri  = isset( $_SERVER['REQUEST_URI'] ) ? wp_unslash( $_SERVER['REQUEST_URI'] ) : ''; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput.InputNotSanitized
	$file = TK_THEME_DIR . '/data/llms.txt';
	$home = (string) wp_parse_url( home_url( '/' ), PHP_URL_PATH );

	if ( untrailingslashit( '' === $home ? '/' : $home ) . '/llms.txt' !== (string) wp_parse_url( $uri, PHP_URL_PATH ) || ! is_readable( $file ) ) {
		return;
	}

	// phpcs:ignore WordPress.WP.AlternativeFunctions.file_get_contents_file_get_contents -- local theme file.
	$body = str_replace( '{{home}}', untrailingslashit( home_url() ), (string) file_get_contents( $file ) );

	status_header( 200 );
	header( 'Content-Type: text/plain; charset=utf-8' );
	header( 'X-Robots-Tag: noindex' );
	if ( 'HEAD' !== ( isset( $_SERVER['REQUEST_METHOD'] ) ? strtoupper( (string) $_SERVER['REQUEST_METHOD'] ) : 'GET' ) ) { // phpcs:ignore WordPress.Security.ValidatedSanitizedInput -- compared only.
		echo $body; // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- plain text by design.
	}
	exit;
}
add_action( 'init', 'tk_serve_llms_txt' );

/**
 * robots.txt: explicit Allow, admin-ajax, no search-result URLs, AI crawlers welcome (search and training),
 * llms.txt pointer. The SEO Framework writes the base file and the Sitemap line on robots_txt at priority 10
 * (replacing the body), so this runs at 20.
 *
 * @param string $output Generated robots.txt.
 * @param bool   $public Whether the site is public.
 * @return string
 */
function tk_robots_txt( $output, $public ) {
	if ( ! $public ) {
		return $output;
	}

	if ( false !== strpos( $output, "User-agent: *\n" ) && false === strpos( $output, "Allow: /\n" ) ) {
		$output = str_replace( "User-agent: *\n", "User-agent: *\nAllow: /\n", $output );
	}

	if ( false === strpos( $output, 'Allow: /wp-admin/admin-ajax.php' ) ) {
		$output = str_replace( "Disallow: /wp-admin/\n", "Disallow: /wp-admin/\nAllow: /wp-admin/admin-ajax.php\n", $output );
	}

	if ( false === strpos( $output, 'Disallow: /?s=' ) ) {
		$output = str_replace( "Allow: /wp-admin/admin-ajax.php\n", "Allow: /wp-admin/admin-ajax.php\nDisallow: /?s=\nDisallow: /search/\n", $output );
	}

	if ( false === strpos( $output, 'User-agent: GPTBot' ) ) {
		$bots    = array( 'GPTBot', 'OAI-SearchBot', 'ChatGPT-User', 'ClaudeBot', 'Claude-SearchBot', 'Claude-User', 'PerplexityBot', 'Perplexity-User', 'Google-Extended', 'Applebot-Extended' );
		$output  = rtrim( $output ) . "\n\n# AI search and assistants are welcome.\n";
		// A crawler that matches a named group ignores the "*" group entirely (RFC 9309 2.2.1), so the group
		// repeats every rule of "*": admin, admin-ajax and no search-result URLs.
		$output .= 'User-agent: ' . implode( "\nUser-agent: ", $bots ) . "\nAllow: /\nDisallow: /wp-admin/\nAllow: /wp-admin/admin-ajax.php\nDisallow: /?s=\nDisallow: /search/\n";
	}

	if ( false === strpos( $output, 'llms.txt' ) ) {
		$output .= "\n# Plain-text summary for AI assistants: " . home_url( '/llms.txt' ) . "\n";
	}

	return $output;
}
add_filter( 'robots_txt', 'tk_robots_txt', 20, 2 );

/**
 * Every page gets a self-referencing canonical, noindex pages included (martinadamus Ruling R21).
 *
 * TSF's own generator returns no canonical at all whenever the robots meta contains "noindex" (hard-coded,
 * not an option). This adds it back through TSF's render-data filter with TSF's own (non-noindex-gated) URL
 * builder, only when TSF left the slot empty — never a duplicate tag. Meta\URI::get_canonical_url() is
 * TSF-internal: if an update renames it, fail safe (no canonical added) instead of a fatal error.
 *
 * @param array $tags_render_data Render data keyed by tag id.
 * @return array
 */
function tk_force_canonical_on_noindex( $tags_render_data ) {
	if ( ! empty( $tags_render_data['canonical'] ) || ! is_singular( 'page' ) ) {
		return $tags_render_data;
	}

	if ( ! class_exists( '\The_SEO_Framework\Meta\URI' ) || ! is_callable( array( '\The_SEO_Framework\Meta\URI', 'get_canonical_url' ) ) ) {
		return $tags_render_data;
	}

	$url = \The_SEO_Framework\Meta\URI::get_canonical_url();

	if ( $url ) {
		$tags_render_data['canonical'] = array(
			'tag'        => 'link',
			'attributes' => array(
				'rel'  => 'canonical',
				'href' => $url,
			),
		);
	}

	return $tags_render_data;
}
add_filter( 'the_seo_framework_meta_render_data', 'tk_force_canonical_on_noindex', 10, 1 );

/**
 * No permalink guessing for unknown URLs (martinadamus R61): WordPress's redirect_guess_404_permalink() 301s a 404
 * to any published page whose slug starts with the last path segment (/kontak/ → /kontakt/), turning typos into
 * soft duplicates. An unknown URL is a real 404 (theme 404.php).
 */
add_filter( 'do_redirect_guess_404_permalink', '__return_false' );

/**
 * No Elementor generator meta (version disclosure, nothing a crawler uses): Elementor skips it when the option
 * elementor_meta_generator_tag is '1' (its "Generator Tag" setting), pinned here rather than in the DB.
 */
add_filter( 'pre_option_elementor_meta_generator_tag', static fn() => '1' );

/**
 * An uppercase page URL (/KONTAKT/) answered 200 with the page — a duplicate the page cache cannot store (its
 * path rule is lowercase only). 301 to the lowercase URL, query kept, only when that lowercase path is a published
 * page: an unknown URL stays a 404, and /wp-*, percent-encoded or other non-slug paths are never touched. Runs
 * before redirect_canonical (10), so the trailing slash is added in the same hop.
 */
function tk_lowercase_redirect() {
	$method = isset( $_SERVER['REQUEST_METHOD'] ) ? strtoupper( (string) $_SERVER['REQUEST_METHOD'] ) : 'GET'; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput -- compared only.
	if ( 'GET' !== $method && 'HEAD' !== $method ) {
		return;
	}

	$uri  = isset( $_SERVER['REQUEST_URI'] ) ? (string) $_SERVER['REQUEST_URI'] : '/'; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput -- matched against a strict pattern below.
	$path = explode( '?', $uri, 2 )[0];
	if ( ! preg_match( '~^/[A-Za-z0-9/-]+/?$~', $path ) || ! preg_match( '~[A-Z]~', $path ) || 0 === stripos( $path, '/wp-' ) ) {
		return;
	}

	$home = (string) wp_parse_url( home_url( '/' ), PHP_URL_PATH );
	$rel  = strtolower( $path );
	if ( '' !== $home && '/' !== $home ) {
		if ( 0 !== strpos( $rel, strtolower( $home ) ) ) {
			return;
		}
		$rel = '/' . substr( $rel, strlen( $home ) );
	}

	$slug = trim( $rel, '/' );
	$page = '' === $slug ? null : get_page_by_path( $slug, OBJECT, 'page' );
	if ( ! $page || 'publish' !== get_post_status( $page ) ) {
		return;
	}

	$query  = isset( $_SERVER['QUERY_STRING'] ) ? (string) $_SERVER['QUERY_STRING'] : ''; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput -- passed through unchanged, like redirect_canonical.
	$target = (int) get_option( 'page_on_front' ) === (int) $page->ID ? home_url( '/' ) : home_url( user_trailingslashit( '/' . $slug ) );
	wp_safe_redirect( $target . ( '' !== $query ? '?' . $query : '' ), 301, 'TK lowercase' );
	exit;
}
add_action( 'template_redirect', 'tk_lowercase_redirect', 1 );

/**
 * One URL per sitemap file. The SEO Framework matches its endpoints by prefix and case-insensitively
 * (/^sitemap\.xml/i, plus a sitemap_index.xml alias of the same sitemap), so /sitemap_index.xml, /sitemap.xml/,
 * /SITEMAP.XML or /sitemap.xml.gz all answered 200 with the sitemap. Every such variant 301s (query dropped: the
 * files take none) to the one URL robots.txt names: /sitemap.xml (and /sitemap.xsl, /sitemap.css for TSF's
 * stylesheets). Runs on init, before TSF answers the request on parse_request.
 */
function tk_sitemap_redirect() {
	$method = isset( $_SERVER['REQUEST_METHOD'] ) ? strtoupper( (string) $_SERVER['REQUEST_METHOD'] ) : 'GET'; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput -- compared only.
	if ( 'GET' !== $method && 'HEAD' !== $method ) {
		return;
	}

	$uri  = isset( $_SERVER['REQUEST_URI'] ) ? (string) $_SERVER['REQUEST_URI'] : '/'; // phpcs:ignore WordPress.Security.ValidatedSanitizedInput -- matched against a strict pattern below.
	$path = explode( '?', $uri, 2 )[0];
	$home = untrailingslashit( (string) wp_parse_url( home_url( '/' ), PHP_URL_PATH ) );
	if ( '' !== $home ) {
		if ( 0 !== stripos( $path, $home . '/' ) ) {
			return;
		}
		$path = substr( $path, strlen( $home ) );
	}

	if ( ! preg_match( '~^/sitemap(_index\.xml|\.(xml|xsl|css))~i', $path, $m ) ) {
		return;
	}

	$file = '/sitemap.' . ( isset( $m[2] ) && '' !== $m[2] ? strtolower( $m[2] ) : 'xml' );
	if ( $file === $path ) {
		return; // The exact file (a query, if any, is ignored by TSF).
	}

	wp_safe_redirect( home_url( $file ), 301, 'TK sitemap' );
	exit;
}
add_action( 'init', 'tk_sitemap_redirect', 1 );

/**
 * TSF's sitemap.xsl / sitemap.css: one coherent header set. TSF sends "Cache-Control: max-age=1800" and adds a
 * second X-Robots-Tag (nofollow) next to its noindex; for text/css Apache's mod_expires (ExpiresByType, the
 * static-asset rule of docs/go-live-requirements.md) then appended "max-age=31536000" to the same header. The
 * callback runs just before PHP sends the headers (after TSF set its own) and replaces them: crawler-file
 * caching like robots.txt and the sitemap (public, one hour), one X-Robots-Tag, and an explicit Expires — which
 * makes mod_expires leave the response alone (it never touches a response that already has an Expires header).
 *
 * @param array $list TSF sitemap endpoints keyed by id.
 * @return array
 */
function tk_sitemap_stylesheet_headers( $list ) {
	foreach ( array( 'xsl-stylesheet', 'css' ) as $id ) {
		if ( empty( $list[ $id ]['callback'] ) || ! is_callable( $list[ $id ]['callback'] ) ) {
			continue;
		}

		$callback                = $list[ $id ]['callback'];
		$list[ $id ]['callback'] = static function ( ...$args ) use ( $callback ) {
			header_register_callback( 'tk_sitemap_stylesheet_send_headers' );
			return $callback( ...$args );
		};
	}

	return $list;
}
add_filter( 'the_seo_framework_sitemap_endpoint_list', 'tk_sitemap_stylesheet_headers', 20 );

/** The header set of tk_sitemap_stylesheet_headers() (registered with header_register_callback()). */
function tk_sitemap_stylesheet_send_headers() {
	header( 'Cache-Control: public, max-age=3600' );
	header( 'Expires: ' . gmdate( 'D, d M Y H:i:s', time() + 3600 ) . ' GMT' );
	header( 'X-Robots-Tag: noindex, nofollow' );
}

/**
 * Search results (/?s=…) are noindex in the response header too, not only in TSF's robots meta: a crawler that
 * fetches a search URL some site linked sees it without parsing the HTML (robots.txt also disallows /?s=).
 */
function tk_search_noindex_header() {
	if ( is_search() && ! headers_sent() ) {
		header( 'X-Robots-Tag: noindex' );
	}
}
add_action( 'template_redirect', 'tk_search_noindex_header', 0 );

/**
 * No feeds. The site publishes pages only (no posts) and comments are closed, so /feed/, /comments/feed/,
 * ?feed=rss2 and every /<page>/feed/ answered 200 with an empty RSS document. They are a real 404 now
 * (martinadamus has no ruling; a 301 to the home page would be a soft 404): the request's query becomes
 * error=404, so WordPress itself sends the 404 status with no-store headers (WP::send_headers()) and renders the
 * theme's 404.php; the page cache never stores a 404 (BYPASS (404)). Feed links are already out of <head>
 * (inc/cleanup.php). Sitemaps and robots.txt are no feeds and are unaffected.
 *
 * @param array $query_vars Parsed query vars.
 * @return array
 */
function tk_no_feeds( $query_vars ) {
	return isset( $query_vars['feed'] ) ? array( 'error' => '404' ) : $query_vars;
}
add_filter( 'request', 'tk_no_feeds' );
